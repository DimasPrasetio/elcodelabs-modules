// STATUS.md: the generated snapshot between its markers, and the checks that keep the whole file
// — and the rule table in AGENTS.md — current as the library grows.

import { spawnSync } from "node:child_process";
import { existsSync, readFileSync, readdirSync } from "node:fs";
import { join } from "node:path";

export const STATUS_BEGIN = "<!-- elco:status:begin -->";
export const STATUS_END = "<!-- elco:status:end -->";

const git = (root, args) => spawnSync("git", args, { cwd: root, encoding: "utf8" });

/** Fixture modules the testbed copies into its library copy: id → module.json. */
function fixtures(root) {
  const out = new Map();
  const walk = (dir) => {
    for (const e of existsSync(dir) ? readdirSync(dir, { withFileTypes: true }) : []) {
      if (!e.isDirectory()) continue;
      const manifest = join(dir, e.name, "module.json");
      if (existsSync(manifest)) out.set(e.name, JSON.parse(readFileSync(manifest, "utf8")));
      else walk(join(dir, e.name));
    }
  };
  walk(join(root, "testbed/fixtures"));
  return out;
}

/**
 * The testbed's scenarios — name, one-line description (from the header comment of
 * scripts/testbed.mjs), and the library modules each installs, directly or as a kit or Go kit
 * of what it installs (fixtures included).
 */
export function testbedScenarios(root, modules) {
  const src = readFileSync(join(root, "scripts/testbed.mjs"), "utf8");
  const byId = new Map(modules.map(({ id, m }) => [id, m]));
  const fix = fixtures(root);

  // Header: "//   name   description" and indented continuation lines, up to "// Each:".
  const header = src.slice(0, src.indexOf("// Each:"));
  const described = new Map();
  let last;
  for (const line of header.split("\n")) {
    const named = line.match(/^\/\/ {3}([a-z0-9-]+) +(.+)$/);
    const more = line.match(/^\/\/ {4,}(\S.*)$/);
    if (named) described.set((last = named[1]), named[2].trim());
    else if (more && last) described.set(last, `${described.get(last)} ${more[1].trim()}`);
    else last = undefined;
  }

  const table = src.match(/const scenarios = \{([^}]*)\}/)?.[1] ?? "";
  const entries = table.split(",").map((s) => s.trim()).filter(Boolean).map((s) => {
    const [name, fn] = s.includes(":") ? s.split(":").map((x) => x.trim().replace(/"/g, "")) : [s, s];
    return { name, fn };
  });

  return entries.map(({ name, fn }) => {
    const start = src.indexOf(`async function ${fn}(`);
    const next = src.indexOf("\nasync function ", start + 1);
    const body = start < 0 ? "" : src.slice(start, next < 0 ? src.indexOf("\nconst scenarios") : next);
    const named = new Set([
      // An install list entry — ["users"] or ["auth", { ports … }] — not an index like
      // modules["x"] nor a list of names like ["ui-core", "ui-data"].
      ...[...body.matchAll(/(?<![\w\])])\[\s*"([a-z][a-z0-9-]*)"\s*(?:\]|,\s*\{)/g)].map((x) => x[1]),
      ...[...body.matchAll(/installModule\([^,]+,\s*[^,]+,\s*"([a-z][a-z0-9-]*)"/g)].map((x) => x[1]),
      ...[...body.matchAll(/cli\("add"((?:,\s*"[^"]*")+)\)/g)].flatMap((x) => [...x[1].matchAll(/"([a-z][a-z0-9-]*)"/g)].map((y) => y[1])),
    ]);
    const installs = new Set();
    const visit = (id) => {
      const m = byId.get(id) ?? fix.get(id);
      if (!m || installs.has(id)) return;
      if (byId.has(id)) installs.add(id);
      for (const k of [...(m.ui ?? []), ...(m.go_kits ?? [])]) visit(k);
    };
    for (const id of named) visit(id);
    return { name, description: described.get(name), installs };
  });
}

/** Problems: a scenario without a description, a module no scenario installs. */
export function checkTestbedCoverage(root, modules, problem) {
  const scenarios = testbedScenarios(root, modules);
  for (const s of scenarios) {
    if (!s.description) problem("scripts/testbed.mjs", `testbed-documented: scenario "${s.name}" has no line in the header comment — describe what it proves`);
  }
  for (const { id } of modules) {
    if (!scenarios.some((s) => s.installs.has(id))) {
      problem(`modules/${id}`, `testbed-covered: no testbed scenario installs ${id} — a module is not done until one does (scripts/testbed.mjs)`);
    }
  }
}

/** The generated snapshot STATUS.md carries between its markers. */
export function statusBlock(root, modules, presets, kernel) {
  const scenarios = testbedScenarios(root, modules);
  const cell = (s) => String(s).replaceAll("|", "\\|");
  const kinds = {};
  for (const { m } of modules) kinds[m.kind] = (kinds[m.kind] ?? 0) + 1;
  return [
    STATUS_BEGIN,
    "<!-- Generated by `node scripts/catalog.mjs` from the manifests and scripts/testbed.mjs — do not edit between these markers. -->",
    "",
    `**Kernel ${kernel}** pinned in [kernel/](kernel/README.md) · **${modules.length} modules** (${Object.entries(kinds).map(([k, n]) => `${n} ${k}`).join(", ")}) · **${presets.length} preset${presets.length === 1 ? "" : "s"}** · **${scenarios.length} testbed scenarios**`,
    "",
    "| Module | Kind | Version | Kernel ≥ | Scoped | Tested in |",
    "|---|---|---|---|---|---|",
    ...modules.map(({ id, m }) => {
      const tested = scenarios.filter((s) => s.installs.has(id)).map((s) => s.name).join(", ") || "**none**";
      return `| [${id}](modules/${id}/README.md) | ${m.kind} | ${m.version} | ${m.requires_kernel} | ${m.scoped ? "yes" : "—"} | ${tested} |`;
    }),
    "",
    "| Preset | Version |",
    "|---|---|",
    ...presets.map(({ id, p }) => `| [${id}](themes/${id}/DESIGN.md) | ${p.version} |`),
    "",
    "| Testbed scenario | Proves |",
    "|---|---|",
    ...scenarios.map((s) => `| \`${s.name}\` | ${cell(s.description ?? "—")} |`),
    STATUS_END,
  ].join("\n");
}

/** STATUS.md with its block replaced; undefined when the markers are missing. */
export function withStatusBlock(text, block) {
  const a = text.indexOf(STATUS_BEGIN);
  const b = text.indexOf(STATUS_END);
  if (a < 0 || b < a) return undefined;
  return text.slice(0, a) + block + text.slice(b + STATUS_END.length);
}

const handWritten = (text) => {
  const a = text.indexOf(STATUS_BEGIN);
  const b = text.indexOf(STATUS_END);
  return a < 0 || b < a ? text : text.slice(0, a) + text.slice(b + STATUS_END.length);
};

const RULE_SOURCES = ["scripts/catalog.mjs", "scripts/lib/rules.mjs", "scripts/lib/kernel.mjs", "scripts/lib/status.mjs"];

/** Rule names in a script's problem calls: each message starting with a rule name and a colon, ternaries too. */
function namesIn(src) {
  const names = new Set();
  for (const call of src.matchAll(/problem\(([\s\S]{0,400}?)\);/g)) {
    for (const x of call[1].matchAll(/[`"]([a-z][a-z-]+): /g)) names.add(x[1]);
  }
  return names;
}

/** Rule names the checks report, from the scripts that report them. */
export function ruleNames(root) {
  return new Set(RULE_SOURCES.flatMap((f) => [...namesIn(readFileSync(join(root, f), "utf8"))]));
}

/** Every rule a check reports is in the rule table of AGENTS.md. */
export function checkRulesDocumented(root, problem) {
  const agents = readFileSync(join(root, "AGENTS.md"), "utf8");
  for (const name of ruleNames(root)) {
    if (!agents.includes(`\`${name}\``)) problem("AGENTS.md", `rules-documented: the check reports "${name}" but the rule table does not list it`);
  }
}

/**
 * With --since: a change that releases a module or preset, moves the kernel, or changes the
 * rules or the testbed's scenarios also changes the hand-written part of STATUS.md (its log,
 * and whatever else it moved) — so the next developer, person or AI, reads where things stand.
 */
export function checkStatusHistory(root, ref, modules, presets, problem) {
  if (git(root, ["rev-parse", "--verify", "--quiet", `${ref}^{commit}`]).status !== 0) return;
  const reasons = [];
  const released = []; // [id, version]: each needs its own line in STATUS.md
  for (const [dir, list, manifest] of [["modules", modules, "module.json"], ["themes", presets, "preset.json"]]) {
    for (const { id, m, p } of list) {
      const now = (m ?? p).version;
      const before = git(root, ["show", `${ref}:${dir}/${id}/${manifest}`]);
      if (before.status !== 0) reasons.push(`${id} ${now} is new`);
      else if (JSON.parse(before.stdout).version !== now) reasons.push(`${id} is now ${now}`);
      else continue;
      released.push([id, now]);
    }
  }
  if (git(root, ["diff", "--quiet", ref, "--", "kernel/kernel.lock.json"]).status !== 0) reasons.push("the pinned kernel moved");
  const oldRules = new Set(RULE_SOURCES.flatMap((f) => {
    const r = git(root, ["show", `${ref}:${f}`]);
    return r.status === 0 ? [...namesIn(r.stdout)] : [];
  }));
  const rules = ruleNames(root);
  if ([...rules].some((r) => !oldRules.has(r)) || [...oldRules].some((r) => !rules.has(r))) reasons.push("the rules changed");
  const oldTestbed = git(root, ["show", `${ref}:scripts/testbed.mjs`]).stdout ?? "";
  const scenarioTable = (s) => s.match(/const scenarios = \{([^}]*)\}/)?.[1] ?? "";
  if (scenarioTable(oldTestbed) !== scenarioTable(readFileSync(join(root, "scripts/testbed.mjs"), "utf8"))) reasons.push("the testbed's scenarios changed");
  if (!reasons.length) return;

  const before = git(root, ["show", `${ref}:STATUS.md`]);
  const now = existsSync(join(root, "STATUS.md")) ? readFileSync(join(root, "STATUS.md"), "utf8") : "";
  const hand = handWritten(now);
  if (before.status === 0 && handWritten(before.stdout) === hand) {
    problem("STATUS.md", `status-current: ${reasons.join("; ")} — update STATUS.md: a Log entry, and Last verified / In progress / Next / Known limits where they moved`);
    return;
  }
  // Each release is named, with its version, on a line this change adds — not covered by an
  // edit about something else, nor by an old line that happens to hold the same words.
  const old = new Set(before.status === 0 ? handWritten(before.stdout).split("\n") : []);
  const lines = hand.split("\n").filter((l) => !old.has(l));
  const named = (id, v) => lines.some((l) => new RegExp(`(^|[^\\w-])${id.replace(/-/g, "\\-")}([^\\w-]|$)`).test(l) && l.includes(v));
  const unnamed = released.filter(([id, v]) => !named(id, v));
  if (unnamed.length) {
    problem("STATUS.md", `status-current: ${unnamed.map(([id, v]) => `${id} ${v}`).join(", ")} released without a new line in STATUS.md naming it with its version (Log)`);
  }
}
